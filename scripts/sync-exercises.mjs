// Run: npm run sync:exercises
// Regenerates lib/exercises/sets.ts from lib/exercises/data/*.json and links
// each topic that has a set to its practice page in lib/grammar/topics.json.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dataDir = new URL("../lib/exercises/data/", import.meta.url);
const files = readdirSync(dataDir).filter((f) => f.endsWith(".json")).sort();
const slugs = files.map((f) => f.slice(0, -".json".length));

const imports = slugs.map((s, i) => `import s${i} from "./data/${s}.json" with { type: "json" };`);
const entries = slugs.map((s, i) => `  "${s}": s${i} as ExerciseSet,`);
const sets = [
  "// Generated by `npm run sync:exercises` — do not edit.",
  'import type { ExerciseSet } from "./types";',
  ...imports,
  "",
  "export const EXERCISE_SETS: Record<string, ExerciseSet> = {",
  ...entries,
  "};",
  "",
].join("\n");
writeFileSync(new URL("../lib/exercises/sets.ts", import.meta.url), sets);

const topicsUrl = new URL("../lib/grammar/topics.json", import.meta.url);
const topics = JSON.parse(readFileSync(topicsUrl, "utf8"));
// Drop practice links whose data file is gone (any other exercises are kept).
for (const t of topics) if (t.exercises?.[0]?.href === `/topics/${t.slug}/practice`) delete t.exercises;
for (const slug of slugs) {
  const t = topics.find((x) => x.slug === slug);
  if (!t) throw new Error(`${slug}.json: no such topic in topics.json`);
  t.exercises = [{ title: "Practice", href: `/topics/${slug}/practice` }];
}
writeFileSync(topicsUrl, JSON.stringify(topics, null, 2) + "\n");
console.log(`synced ${slugs.length} exercise sets`);
